from collections.abc import Callable
from datetime import datetime
from typing import Any, Protocol, Self

from app.domain.models import Session, User

Document = dict[str, Any]


class Resources(Protocol):
    async def get(self, kind: str, key: str) -> Document | None: ...
    async def put(self, kind: str, key: str, data: Document, create: bool = False) -> None: ...
    async def list(self, kind: str, filters: Document | None = None) -> list[Document]: ...
    async def delete(self, kind: str, key: str) -> None: ...
    async def claim_job(self) -> Document | None: ...


class Users(Protocol):
    async def get(self, user_id: str) -> User | None: ...
    async def by_email(self, email: str) -> User | None: ...
    async def add(self, user: User) -> None: ...


class Sessions(Protocol):
    async def get(self, session_id: str) -> Session | None: ...
    async def save(self, session: Session) -> None: ...
    async def add_refresh(self, token_hash: str, session_id: str) -> None: ...
    async def refresh_record(self, token_hash: str) -> tuple[str, bool] | None: ...
    async def consume(self, token_hash: str) -> None: ...


class UnitOfWork(Protocol):
    resources: Resources
    users: Users
    sessions: Sessions

    async def __aenter__(self) -> Self: ...
    async def __aexit__(self, exc_type, exc_val, traceback) -> None: ...
    async def lock(self, key: str) -> None: ...


UowFactory = Callable[[], UnitOfWork]


class Security(Protocol):
    def password_hash(self, password: str) -> str: ...
    def password_matches(self, password: str, encoded: str) -> bool: ...
    def access_token(self, user_id: str, session_id: str) -> str: ...
    def decode(self, token: str) -> Document: ...


class Model(Protocol):
    enabled: bool
    model_id: str

    async def complete(self, task: str, context: Document) -> Document: ...


class SourceFetcher(Protocol):
    async def collect(self, source: Document, published_from: datetime | None = None) -> list[Document]: ...
